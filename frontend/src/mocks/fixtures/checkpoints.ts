export function createFullCheckpointPlan(): Plan {
  const base = planSchema.parse(createScenario().plan);
  const technicalStep = base.steps[0]!;
  const steps = catalog.map((entry): Plan['steps'][number] => ({
    id: `step_${entry.key}`,
    title: entry.title,
    description: entry.title,
    status: 'not_started',
    request_ids: [],
    allowed_statuses: entry.policy === 'mentor' ? [] : ['in_progress', 'completed'],
    blocked_reason: null,
    template_key: entry.key,
    period: entry.period,
    completion_policy: entry.policy,
    confirmations: [],
    revision: 1,
    allowed_actions: entry.policy === 'mentor' ? [] : ['confirm'],
    awaiting_role: null,
    instructions: entry.instructions,
    resources: entry.resources ?? [],
  }));

  return planSchema.parse({
    ...base,
    next_step_id: technicalStep.id,
    steps: [technicalStep, ...steps],
  });
}
